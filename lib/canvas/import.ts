import { parseDesignDocument, type DesignDocument } from '@/lib/design/document'
import {
  identifyLayers,
  materializeOutput,
  outputDimensions,
  storyForOutput,
  type CreativeSetDocument,
} from '@/lib/creative-sets/document'
import { resolvedDocumentHash } from '@/lib/creative-sets/delivery'
import { documentCanvasSize } from '@/lib/export/adapt'
import { artboardSchema, type Artboard } from './document'
import { ARTBOARD_GAP } from './layout'

/**
 * Bring existing native documents onto a canvas. Each becomes an artboard
 * holding a lossless copy and a pin to exactly what was copied (id,
 * revision, time and document hash). Sources are never written: a project,
 * Story Set or approved campaign design stays as it was, and its later
 * changes never flow in silently.
 */

type Placement = { x: number; y: number; newId?: () => string; now?: Date }

/** Lay copies out left to right from a point. */
function row<T extends { document: DesignDocument }>(
  items: readonly T[],
  at: { x: number; y: number }
) {
  let x = at.x
  return items.map((item) => {
    const position = { x, y: at.y }
    x += documentCanvasSize(item.document).width + ARTBOARD_GAP
    return { item, position }
  })
}

/** A cloud project as one artboard. */
export async function artboardFromProject(
  project: { id: string; name: string; revision: number; document: unknown },
  { x, y, newId = () => crypto.randomUUID(), now = new Date() }: Placement
): Promise<Artboard> {
  const source = parseDesignDocument(project.document)
  return artboardSchema.parse({
    id: newId(),
    name: project.name.slice(0, 120) || 'Project',
    x,
    y,
    document: identifyLayers(source, newId),
    origin: {
      kind: 'project',
      id: project.id,
      revision: project.revision,
      copiedAt: now.toISOString(),
      documentHash: await resolvedDocumentHash(source),
    },
  })
}

/** A campaign design (often generated by the launch pipeline) as one artboard. */
export async function artboardFromDesign(
  design: { id: string; name: string; campaignId: string | null; document: unknown },
  { x, y, newId = () => crypto.randomUUID(), now = new Date() }: Placement
): Promise<Artboard> {
  const source = parseDesignDocument(design.document)
  return artboardSchema.parse({
    id: newId(),
    name: design.name.slice(0, 120) || 'Campaign design',
    x,
    y,
    document: identifyLayers(source, newId),
    origin: {
      kind: 'design',
      id: design.id,
      campaignId: design.campaignId,
      copiedAt: now.toISOString(),
      documentHash: await resolvedDocumentHash(source),
    },
    ...(design.campaignId ? { context: { campaignId: design.campaignId } } : {}),
  })
}

/**
 * Every main-editor output of a saved Story Set, with its linked copy
 * resolved, as artboards in story order. Store groups keep their own
 * renderer and stay in the Story Set.
 */
export async function artboardsFromStorySet(
  set: { id: string; name: string; revision: number; document: CreativeSetDocument },
  { x, y, newId = () => crypto.randomUUID(), now = new Date() }: Placement
): Promise<Artboard[]> {
  const ordered = set.document.stories.flatMap((story) =>
    set.document.outputs.filter((output) => output.storyId === story.id)
  )
  const resolved = ordered.map((output) => ({
    output,
    document: materializeOutput(set.document, output),
  }))
  const placed = []
  for (const { item, position } of row(resolved, { x, y })) {
    const story = storyForOutput(set.document, item.output)
    placed.push(
      artboardSchema.parse({
        id: newId(),
        name: `${story.headline.slice(0, 80)} · ${outputDimensions(item.output).name}`,
        ...position,
        document: identifyLayers(item.document, newId),
        origin: {
          kind: 'story-set',
          id: set.id,
          outputId: item.output.id,
          revision: set.revision,
          copiedAt: now.toISOString(),
          documentHash: await resolvedDocumentHash(item.document),
        },
      })
    )
  }
  return placed
}
